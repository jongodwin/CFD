'use strict';
// Regenerates js/example.js: a noisy but realistic sampling campaign on the test circuit.
const fs = require('fs');
const path = require('path');
const { makeModel } = require('../test/circuit.js');

const { model } = makeModel({ sizes: true, assays: true, sizeAssays: true }, 7);
const pos = { n1: [270, 190], n2: [540, 190], n3: [800, 190] };
model.nodes.forEach((n) => { [n.x, n.y] = pos[n.id]; });
const ends = { s1: { fx: 70, fy: 190 }, s5: { tx: 940, ty: 70 }, s6: { tx: 940, ty: 330 } };
const r = (v, d) => (v == null ? null : Number(v.toFixed(d)));
model.streams.forEach((s) => {
  Object.assign(s, ends[s.id] || {});
  s.flow = r(s.flow, 1);
  s.psd = s.psd.map((v) => r(v, 1));
  s.assay = s.assay.map((v) => r(v, 2));
  s.sizeAssay = s.sizeAssay.map((row) => row.map((v) => r(v, 2)));
});
model.flowUnit = 't/h';
fs.writeFileSync(path.join(__dirname, '../js/example.js'),
  '/* Example sampling campaign (generated by tools/make-example.js). */\nwindow.MB_EXAMPLE = ' + JSON.stringify(model, null, 1) + ';\n');
